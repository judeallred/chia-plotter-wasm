"""Validates v2 plots of any k, using the same chia_rs calls as `chia plots check`.

`chia plots check` (chia/plotting/check_plots.py) solves and validates proofs with the
network constant PLOT_SIZE_V2 (28), so it can only check k28 plots. This script runs the
same steps with the k stored in the plot, which lets us test small plots quickly:

  1. get_qualities_for_challenge(challenge)          -> partial proofs
  2. solve_proof(partial, plot_id, strength, k, ...)  -> full proof
  3. validate_proof_v2(plot_id, k, challenge, ...)    -> quality string, must match

It also checks the plot memo and that the file name matches the plot ID.

Proof checks alone can miss damage: a corrupted chunk usually just yields fewer proofs.
With --reference, the plot is also regenerated by the native build of the same plotter
(core/build-native/pos2w_cli) from the plot ID and memo in its header, and the two files
must be byte for byte identical. Plotting is deterministic, so this is an exact check.

Usage: python -I check_plot.py [-n challenges] [--testnet] [--reference pos2w_cli] plot2 [plot2 ...]
Exit code is non-zero if any plot fails.
"""

from __future__ import annotations

import argparse
import filecmp
import subprocess
import tempfile
import sys
import time
from pathlib import Path

from chia_rs import G1Element, PrivateKey, Prover, solve_proof, validate_proof_v2
from chia_rs.sized_bytes import bytes32

from chia.util.hash import std_hash


def check(path: Path, challenges: int, testnet: bool, reference: Path | None) -> bool:
    prover = Prover(str(path))
    k = prover.size()
    strength = prover.get_strength()
    plot_id = prover.plot_id()
    memo = prover.get_memo()
    print(f"{path.name}: k={k} strength={strength} index={prover.get_plot_index()} meta_group={prover.get_meta_group()}")

    ok = True
    if f"-{plot_id.hex()}." not in path.name:
        print("  FAIL file name does not contain the plot ID")
        ok = False
    # The memo is pool (48 byte key or 32 byte puzzle hash) + farmer key (48) + secret key (32).
    if len(memo) not in (48 + 48 + 32, 32 + 48 + 32):
        print(f"  FAIL memo has unexpected length {len(memo)}")
        ok = False
    else:
        try:
            G1Element.from_bytes(memo[-80:-32])
            PrivateKey.from_bytes(memo[-32:])
        except Exception as e:
            print(f"  FAIL memo keys do not parse: {e}")
            ok = False

    found = 0
    valid = 0
    start = time.monotonic()
    for i in range(challenges):
        challenge = std_hash(i.to_bytes(32, "big"))
        for partial in prover.get_qualities_for_challenge(challenge):
            found += 1
            try:
                full = solve_proof(partial, plot_id, strength, k, testnet)
                quality = validate_proof_v2(plot_id, k, challenge, strength, full, testnet)
            except Exception as e:
                print(f"  FAIL challenge {i}: {type(e).__name__}: {e}")
                ok = False
                continue
            if quality is not None and quality == partial.get_string(strength):
                valid += 1
            else:
                print(f"  FAIL challenge {i}: proof does not validate")
                ok = False
    elapsed = time.monotonic() - start
    if found == 0:
        print("  FAIL no proofs found")
        ok = False
    if reference is not None:
        with tempfile.TemporaryDirectory() as tmp:
            ref = Path(tmp) / "ref.plot2"
            subprocess.run(
                [str(reference), str(ref), str(k), str(strength), plot_id.hex(), memo.hex(), str(int(testnet)),
                 str(prover.get_plot_index()), str(prover.get_meta_group())],
                check=True, capture_output=True,
            )
            if filecmp.cmp(ref, path, shallow=False):
                print("  reference: byte-identical to native plotter")
            else:
                print("  FAIL reference: differs from native plotter output")
                ok = False
    print(f"  proofs {valid}/{found} valid over {challenges} challenges ({elapsed:.1f}s) {'OK' if ok else 'FAILED'}")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("-n", "--challenges", type=int, default=30)
    parser.add_argument("--testnet", action="store_true")
    parser.add_argument("--reference", type=Path, help="path to native pos2w_cli")
    parser.add_argument("plots", nargs="+", type=Path)
    args = parser.parse_args()
    results = [check(p, args.challenges, args.testnet, args.reference) for p in args.plots]
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
