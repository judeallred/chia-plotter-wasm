"""Validates v2 plot group files of any k, using the same chia_rs calls as `chia plots check`.

`chia plots check` (chia/plotting/check_plots.py) refuses v2 plots whose k differs from the
network constant PLOT_SIZE_V2 (28 on mainnet), so it can only check k28 plots. This script
runs the same steps with the k stored in the plot, which lets us test small plots quickly:

  1. Prover(plot).get_qualities_for_challenge(challenge), deduplicated by plot index and
     chain as chia's V2Prover does                       -> partial proofs
  2. solve_proof(partial, plot_id_for_index(i), strength, k) -> full proof
  3. validate_proof_v2(group_id, i, k, strength, meta_group, challenge, proof)
                                                          -> quality string, must match

It also checks the plot memo and that the file name matches the plot group ID.

Proof checks alone can miss damage: a corrupted chunk usually just yields fewer proofs.
With --reference, the plot is also regenerated by the native build of the same plotter
(core/build-native/pos2w_cli) from the group ID and memo in its header, and the two files
must be byte for byte identical. Plotting is deterministic, so this is an exact check. It
only applies to groups of one plot (index 0), the only kind pos2-chip writes today.

Usage: python -I check_plot.py [-n challenges] [--reference pos2w_cli] gplot [gplot ...]
Exit code is non-zero if any plot fails.
"""

from __future__ import annotations

import argparse
import filecmp
import subprocess
import tempfile
import sys
import time
from pathlib import Path

from chia_rs import G1Element, PrivateKey, Prover, solve_proof, validate_proof_v2
from chia_rs.sized_ints import uint8, uint16

from chia.util.hash import std_hash


def check(path: Path, challenges: int, reference: Path | None) -> bool:
    prover = Prover(str(path))
    k = prover.size()
    strength = prover.get_strength()
    meta_group = prover.get_meta_group()
    group_size = prover.get_group_size()
    group_id = prover.plot_group_id()
    memo = prover.get_memo()
    print(f"{path.name}: k={k} strength={strength} group_size={group_size} meta_group={meta_group}")

    ok = True
    if f"-{group_id.hex()}" not in path.name:
        print("  FAIL file name does not contain the plot group ID")
        ok = False
    # The memo is pool (48 byte key or 32 byte puzzle hash) + farmer key (48) + secret key (32).
    if len(memo) not in (48 + 48 + 32, 32 + 48 + 32):
        print(f"  FAIL memo has unexpected length {len(memo)}")
        ok = False
    else:
        try:
            G1Element.from_bytes(memo[-80:-32])
            PrivateKey.from_bytes(memo[-32:])
        except Exception as e:
            print(f"  FAIL memo keys do not parse: {e}")
            ok = False

    found = 0
    valid = 0
    start = time.monotonic()
    for i in range(challenges):
        challenge = std_hash(i.to_bytes(32, "big"))
        qualities = {(q.plot_index, q.chain.to_bytes()): q for q in prover.get_qualities_for_challenge(challenge)}
        for q in qualities.values():
            found += 1
            try:
                full = solve_proof(q.chain, prover.plot_id_for_index(q.plot_index), strength, k)
                quality = validate_proof_v2(
                    group_id, uint16(q.plot_index), k, strength, uint8(meta_group), challenge, full
                )
            except Exception as e:
                print(f"  FAIL challenge {i}: {type(e).__name__}: {e}")
                ok = False
                continue
            if quality is not None and quality == q.chain.get_string(uint8(strength)):
                valid += 1
            else:
                print(f"  FAIL challenge {i}: proof for plot index {q.plot_index} does not validate")
                ok = False
    elapsed = time.monotonic() - start
    if found == 0:
        print("  FAIL no proofs found")
        ok = False
    if reference is not None:
        if group_size != 1:
            print("  FAIL reference: only groups of one plot can be regenerated")
            ok = False
        else:
            with tempfile.TemporaryDirectory() as tmp:
                ref = Path(tmp) / "ref.gplot"
                subprocess.run(
                    [str(reference), str(ref), str(k), str(strength), group_id.hex(), memo.hex(), "0",
                     str(meta_group)],
                    check=True, capture_output=True,
                )
                if filecmp.cmp(ref, path, shallow=False):
                    print("  reference: byte-identical to native plotter")
                else:
                    print("  FAIL reference: differs from native plotter output")
                    ok = False
    print(f"  proofs {valid}/{found} valid over {challenges} challenges ({elapsed:.1f}s) {'OK' if ok else 'FAILED'}")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("-n", "--challenges", type=int, default=30)
    parser.add_argument("--reference", type=Path, help="path to native pos2w_cli")
    parser.add_argument("plots", nargs="+", type=Path)
    args = parser.parse_args()
    results = [check(p, args.challenges, args.reference) for p in args.plots]
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
