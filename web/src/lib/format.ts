// Number and time formatting shared by the page and the stats panel.

export function fmtBytes(n: number): string {
  if (n >= 1e12) return `${(n / 1e12).toFixed(2)} TB`;
  if (n >= 1e9) return `${(n / 1e9).toFixed(2)} GB`;
  if (n >= 1e6) return `${(n / 1e6).toFixed(1)} MB`;
  return `${(n / 1e3).toFixed(0)} kB`;
}

export function fmtMs(ms: number): string {
  const s = ms / 1000;
  if (s < 60) return `${s.toFixed(1)} s`;
  return `${Math.floor(s / 60)}m ${Math.round(s % 60)}s`;
}

export function fmtAgo(t: number): string {
  const m = Math.round((Date.now() - t) / 60000);
  if (m < 1) return "just now";
  if (m < 60) return `${m} min ago`;
  const h = Math.round(m / 60);
  if (h < 24) return `${h} h ago`;
  return new Date(t).toLocaleDateString();
}

// "45 minutes" or "1.3 hours".
export function fmtInterval(minutes: number): string {
  return minutes >= 60 ? `${(minutes / 60).toFixed(1)} hours` : `${Math.round(minutes)} minutes`;
}

// A count with one decimal below 10, for rates like "about 4.5 times a day".
export function fmtRate(n: number): string {
  return n.toFixed(n < 10 ? 1 : 0);
}

export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
}
